import {test,expect} from './fixtures';
test('B findings, nested dialogs, report and editing invalidation',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.setViewportSize({width:1920,height:1080});
 await expect(page.getByRole('heading',{name:/把三份材料，/})).toBeVisible();
 await page.screenshot({path:'../test-results/start-page-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'../test-results/start-page-mobile.png',fullPage:true});
 await page.setViewportSize({width:1366,height:900});
 await expect(page.locator('.demo-banner')).toHaveCount(0);
 await page.getByRole('button',{name:'演示中心',exact:true}).click();
 const demos=page.getByRole('dialog',{name:'演示中心',exact:true});
 await expect(demos.getByRole('link',{name:'下载 A 组样例',exact:true})).toBeVisible();
 await expect(demos.getByRole('link',{name:'下载 B 组与标注清单',exact:true})).toBeVisible();
 await page.screenshot({path:'../test-results/demo-center-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 expect(await demos.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
 await page.screenshot({path:'../test-results/demo-center-mobile.png'});
 await page.setViewportSize({width:1366,height:900});
 await page.getByRole('button',{name:'载入 B 组 · 异常'}).click();
 await expect(demos).toHaveCount(0);
 await expect(page.locator('.issue-panel')).toHaveCount(0);
 await page.getByRole('button',{name:'已核对字段，进入下一步'}).click();
 await expect(page.getByRole('region',{name:'核对准备'})).toBeVisible();
 await expect(page.locator('.issue-panel')).toHaveCount(0);
 await page.getByRole('button',{name:'开始交叉核对'}).click();
 await page.locator('.issue-panel tbody tr').filter({hasText:'型号不一致'}).first().click();
 const issue=page.getByRole('dialog',{name:'问题详情',exact:true});
 await expect(issue.getByText('型号：MX24',{exact:true})).toBeVisible();
 await issue.getByRole('button',{name:'查看完整原文'}).first().click();
 await expect(page.getByRole('dialog',{name:'文档原文',exact:true})).toBeVisible();
 await page.keyboard.press('Escape');
 await expect(issue).toBeVisible();
 await issue.locator('select').selectOption('已确认');
 await issue.locator('textarea').fill('已核对原文，确认型号差异');
 await issue.getByRole('button',{name:'保存人工判断'}).click();
 await expect(issue).toHaveCount(0);
 await page.getByRole('button',{name:'审核报告',exact:true}).click();
 const report=page.getByRole('dialog',{name:'审核报告',exact:true});
 await expect(report.getByText('整体人工复核：尚未完成')).toBeVisible();
 const download=page.waitForEvent('download');
 await report.getByRole('link',{name:'导出过程报告'}).click();
 await (await download).saveAs('../test-results/staged-report.docx');
 await page.keyboard.press('Escape');
 await page.screenshot({path:'../test-results/staged-results.png',fullPage:true});
 await page.getByRole('button',{name:'材料管理',exact:true}).click();
 const materials=page.getByRole('dialog',{name:'已提交材料',exact:true});
 await materials.getByRole('button',{name:'修正字段'}).first().click();
 const editor=page.getByRole('dialog',{name:'修正抽取结果',exact:true});
 await expect(editor).toBeVisible();
 await editor.getByLabel('采购方',{exact:true}).fill('人工修改采购方');
 await editor.getByRole('button',{name:'保存修改记录'}).click();
 await expect(editor).toHaveCount(0);
 await page.keyboard.press('Escape');
 await expect(page.locator('.issue-panel')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'已核对字段，进入下一步'})).toBeVisible();
 await page.getByRole('button',{name:'修改记录',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'人工修改记录',exact:true}).getByText('第 1 次人工修改')).toBeVisible();
 await page.keyboard.press('Escape');
 expect(errors).toEqual([]);
});
